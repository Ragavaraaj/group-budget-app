/**
 * Turning the reviewer's findings into a GitHub review. Inline comments are only accepted on lines
 * the diff shows, so findings elsewhere go into the review's body instead of failing the review.
 */

export type Severity = 'blocking' | 'nit';

export interface Finding {
  path: string;
  line: number;
  severity: Severity;
  title: string;
  body: string;
}

export const REVIEW_MARKER = '<!-- sdlc:review -->';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

/** The new-file line numbers each hunk of a unified diff shows (added and context lines). */
export function commentableLines(patch: string | undefined): Set<number> {
  const lines = new Set<number>();
  if (!patch) return lines;
  let line = 0;
  for (const text of patch.split('\n')) {
    const hunk = /^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@/.exec(text);
    if (hunk?.[1]) {
      line = Number(hunk[1]);
      continue;
    }
    if (line === 0 || text.startsWith('\\')) continue;
    if (text.startsWith('-')) continue;
    lines.add(line);
    line++;
  }
  return lines;
}

export function findingBody(finding: Finding): string {
  const label = finding.severity === 'blocking' ? '🔴 **Blocking**' : '🟡 **Nit (optional)**';
  return `${REVIEW_MARKER}\n${label}: ${finding.title}\n\n${finding.body.trim()}`;
}

export interface ReviewPayload {
  body: string;
  comments: { path: string; line: number; side: 'RIGHT'; body: string }[];
}

/** Splits findings into inline comments and body notes, and writes the review's summary. */
export function buildReview(
  findings: Finding[],
  summary: string,
  patches: Record<string, string | undefined>,
): ReviewPayload {
  const inline: ReviewPayload['comments'] = [];
  const elsewhere: Finding[] = [];
  for (const finding of findings) {
    if (commentableLines(patches[finding.path]).has(finding.line)) {
      inline.push({
        path: finding.path,
        line: finding.line,
        side: 'RIGHT',
        body: findingBody(finding) + FOOTER,
      });
    } else {
      elsewhere.push(finding);
    }
  }
  const blocking = findings.filter((f) => f.severity === 'blocking').length;
  const nits = findings.length - blocking;
  const parts = [
    REVIEW_MARKER,
    `### AI review: ${blocking === 0 ? 'no blocking findings' : `${blocking} blocking`}${nits ? `, ${nits} nit${nits === 1 ? '' : 's'}` : ''}`,
    '',
    summary.trim(),
  ];
  if (elsewhere.length > 0) {
    parts.push('', '**Findings outside the diff:**', '');
    for (const f of elsewhere) {
      parts.push(
        `- \`${f.path}:${f.line}\` ${f.severity === 'blocking' ? '🔴' : '🟡'} ${f.title}: ${f.body.trim()}`,
      );
    }
  }
  return { body: parts.join('\n') + FOOTER, comments: inline };
}

export function withFooter(body: string): string {
  return body.includes('Generated by [Claude Code]') ? body : body.trim() + FOOTER;
}
