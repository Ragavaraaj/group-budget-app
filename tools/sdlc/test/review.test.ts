import { describe, expect, it } from 'vitest';
import { buildReview, commentableLines, REVIEW_MARKER, withFooter } from '../src/review.ts';

const PATCH = [
  '@@ -10,4 +10,5 @@ export function x() {',
  ' const a = 1;',
  '-const b = 2;',
  '+const b = 3;',
  '+const c = 4;',
  ' return a;',
  '\\ No newline at end of file',
  '@@ -40,2 +41,2 @@',
  ' end();',
  '+more();',
].join('\n');

describe('commentableLines', () => {
  it('lists the new-file lines a diff shows, skipping removed lines', () => {
    expect([...commentableLines(PATCH)]).toEqual([10, 11, 12, 13, 41, 42]);
  });

  it('is empty for a file without a patch (binary, or too large)', () => {
    expect(commentableLines(undefined).size).toBe(0);
  });
});

describe('buildReview', () => {
  const findings = [
    {
      path: 'src/x.ts',
      line: 11,
      severity: 'blocking' as const,
      title: 'Wrong value',
      body: 'b should stay 2.',
    },
    { path: 'src/x.ts', line: 99, severity: 'nit' as const, title: 'Name', body: 'Rename c.' },
    { path: 'docs/y.md', line: 3, severity: 'nit' as const, title: 'Typo', body: 'teh → the' },
  ];

  it('comments inline where the diff allows and lists the rest in the body', () => {
    const review = buildReview(findings, 'Mostly fine.', { 'src/x.ts': PATCH });
    expect(review.comments).toHaveLength(1);
    expect(review.comments[0]).toMatchObject({ path: 'src/x.ts', line: 11, side: 'RIGHT' });
    expect(review.comments[0]?.body).toContain('🔴 **Blocking**: Wrong value');
    expect(review.comments[0]?.body.startsWith(REVIEW_MARKER)).toBe(true);
    expect(review.body).toContain('### AI review: 1 blocking, 2 nits');
    expect(review.body).toContain('`src/x.ts:99` 🟡 Name: Rename c.');
    expect(review.body).toContain('`docs/y.md:3` 🟡 Typo');
    expect(review.body).toContain('Generated by [Claude Code](https://claude.ai/code)');
  });

  it('says so when there is nothing blocking', () => {
    expect(buildReview([], 'Looks good.', {}).body).toContain(
      '### AI review: no blocking findings',
    );
  });
});

describe('withFooter', () => {
  it('adds the attribution footer once', () => {
    const once = withFooter('Fixed in abc123.');
    expect(withFooter(once)).toBe(once);
    expect(once).toMatch(/Fixed in abc123\.\n\n---\n_Generated by/);
  });
});
